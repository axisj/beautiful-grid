import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { getEncoding } from 'js-tiktoken';

const repositoryRoot = path.resolve(import.meta.dirname, '..');
const siteRoot = path.join(repositoryRoot, 'site');
const distRoot = path.join(siteRoot, 'dist');
const generatedMetricsPath = path.join(siteRoot, 'src/data/aiContextMetrics.ts');
const benchmarkSlugs = [
  'getting-started',
  'data-and-columns',
  'editing',
  'sorting-filtering',
  'cell-merge',
  'virtual-scroll',
];

async function assertMarkdownRouteCoverage() {
  const localeConfigurations = [
    { sourceDirectory: path.join(siteRoot, 'src/content/learn'), outputDirectory: path.join(distRoot, 'learn') },
    { sourceDirectory: path.join(siteRoot, 'src/content/learn/en'), outputDirectory: path.join(distRoot, 'en/learn') },
  ];

  let guideCount = 0;
  for (const configuration of localeConfigurations) {
    const sourceFiles = (await readdir(configuration.sourceDirectory, { withFileTypes: true }))
      .filter(entry => entry.isFile() && /\.mdx?$/.test(entry.name));
    guideCount += sourceFiles.length;
    for (const sourceFile of sourceFiles) {
      const slug = sourceFile.name.replace(/\.mdx?$/, '');
      await readFile(path.join(configuration.outputDirectory, `${slug}.md`), 'utf8');
    }
  }

  await Promise.all([
    readFile(path.join(distRoot, 'api/props.md'), 'utf8'),
    readFile(path.join(distRoot, 'en/api/props.md'), 'utf8'),
    readFile(path.join(distRoot, 'llms.txt'), 'utf8'),
  ]);

  return guideCount;
}

async function measure() {
  const guideCount = await assertMarkdownRouteCoverage();
  const encoding = getEncoding('o200k_base');
  let htmlTokens = 0;
  let markdownTokens = 0;

  try {
    for (const slug of benchmarkSlugs) {
      const [html, markdown] = await Promise.all([
        readFile(path.join(distRoot, `en/learn/${slug}/index.html`), 'utf8'),
        readFile(path.join(distRoot, `en/learn/${slug}.md`), 'utf8'),
      ]);
      htmlTokens += encoding.encode(html).length;
      markdownTokens += encoding.encode(markdown).length;
    }
  } finally {
    encoding.free?.();
  }

  if (markdownTokens >= htmlTokens) {
    throw new Error(`Markdown context (${markdownTokens}) did not reduce raw HTML context (${htmlTokens}).`);
  }

  return {
    tokenSavingsPercent: Math.round((1 - markdownTokens / htmlTokens) * 100),
    htmlTokens,
    markdownTokens,
    guideCount,
    benchmarkGuideCount: benchmarkSlugs.length,
    benchmarkSlugs,
    measurement: {
      tokenizer: 'o200k_base',
      baseline: 'combined raw HTML responses',
      optimized: 'combined Markdown alternate responses',
      locale: 'en',
      excludes: 'agent reasoning, generated output, and tool-call overhead',
    },
  };
}

function serialize(metrics) {
  return `// Generated by scripts/measure-ai-context.mjs. Do not edit manually.\nexport const aiContextMetrics = ${JSON.stringify(metrics, null, 2)} as const;\n`;
}

async function main() {
  const argumentsSet = new Set(process.argv.slice(2));
  if (argumentsSet.has('--write') && argumentsSet.has('--check')) {
    throw new Error('Use either --write or --check, not both.');
  }

  const metrics = await measure();
  const generatedSource = serialize(metrics);

  if (argumentsSet.has('--write')) {
    await writeFile(generatedMetricsPath, generatedSource, 'utf8');
  } else if (argumentsSet.has('--check')) {
    const currentSource = await readFile(generatedMetricsPath, 'utf8');
    if (currentSource !== generatedSource) {
      throw new Error('AI context metrics are stale. Run npm run update:ai-context-metrics.');
    }
  }

  console.log(`Raw HTML context: ${metrics.htmlTokens} tokens`);
  console.log(`Markdown context: ${metrics.markdownTokens} tokens`);
  console.log(`Token reduction: ${metrics.tokenSavingsPercent}%`);
  console.log(`Markdown routes verified: ${metrics.guideCount} guides + 2 API references`);
  if (argumentsSet.has('--check')) console.log('AI context metrics verified');
}

await main();
